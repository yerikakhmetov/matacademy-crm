-- Міндетті пәндер: Қазақстан тарихы және Математикалық сауаттылық —
-- 6000 ₸ бір оқушыдан 8 сабаққа.
--
-- Ескерту: «Математикалық сауаттылық» атауында «математик» бар, сондықтан
-- алдыңғы миграция оған 8000/12 қойып үлгерген. Мұндағы UPDATE шартсыз
-- жазады да, соны түзейді.
UPDATE "Subject"
SET "teacherRate" = 6000, "teacherRateLessons" = 8
WHERE "name" ILIKE '%сауат%'
   OR "name" ILIKE '%грамотн%'
   OR "name" ILIKE '%тарих%'
   OR "name" ILIKE '%истори%';
